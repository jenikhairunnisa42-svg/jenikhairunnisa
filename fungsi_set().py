# konversi string ke set
data = set('abcda') 
print('data', data) 
# output ➜ data {'c', 'b', 'a', 'd'}

# konversi list ke set
data = set(['a', 'b', 'c', 'd', 'a']) 
print('data', data)
 # output ➜ data {'c', 'b', 'a', 'd'}

#konversi tuple ke set
data = set(('a', 'b', 'c', 'd', 'a'))
print('data', data) 
# output ➜ data {'c', 'b', 'a', 'd'}

#konversi range ke set
data = set(range(1, 5)) 
print('data', data) 
# output ➜ data {1, 2, 3, 4}